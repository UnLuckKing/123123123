export function getClientLocale(): string {
  const nav = (navigator.language || (navigator as any).userLanguage || "tr").toLowerCase().replace("-", "_");
  if (nav.startsWith("zh_tw") || nav.startsWith("zh_hk") || nav.startsWith("zh_hant")) return "zh-TW";
  if (nav.startsWith("zh")) return "zh";
  const prefix = nav.split("_")[0];
  if (NO_ACCOUNT_I18N[prefix]) return prefix;
  return "tr";
}

export function getNoAccountStrings(locale?: string): NoAccountText {
  const loc = locale || getClientLocale();
  return NO_ACCOUNT_I18N[loc] || NO_ACCOUNT_I18N["tr"] || NO_ACCOUNT_I18N["en"];
}

export function isNoAccountError(errStr: string): boolean {
  if (!errStr) return false;
  const lower = errStr.toLowerCase();
  return (
    lower.includes("err_no_riot_account") ||
    lower.includes("no active riot account") ||
    lower.includes("no_active_riot_account") ||
    lower.includes("hesaba giriş yap") ||
    lower.includes("log in to your account") ||
    lower.includes("authentication timeout") ||
    lower.includes("session authentication") ||
    lower.includes("slot terminated on mac (404)") ||
    lower.includes("slot terminated") ||
    lower.includes("not_found") ||
    lower.includes("404")
  );
}
